"""Generate the C++ parameter table from firmware/gen/params.json.

The manifest is the source of truth. This keeps the JUCE APVTS, the engine ids
and the editor names in one place. The APVTS key is the stable manifest name.
The engine id is the manifest index.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import TypedDict, cast


class ParamDoc(TypedDict):
    """One generated manifest row."""

    id: int
    name: str
    target: str
    min: int
    max: int
    default: int
    curve: str
    unit: str
    rate: str
    modulatable: bool
    display: str


class ParamsDoc(TypedDict):
    """The generated params.json document."""

    params: list[ParamDoc]


def display_name(name: str) -> str:
    part = ""
    if name.endswith(".p0") or name.endswith(".p1"):
        part = f" p{int(name[-1]) + 1}"
        name = name[:-3]
    name = name.replace("_", " ").replace(".", " ")
    return name + part


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: gen_params.py params.json Params.h", file=sys.stderr)
        return 2
    source = Path(sys.argv[1])
    target = Path(sys.argv[2])
    raw = cast(object, json.loads(source.read_text(encoding="utf-8")))
    data = cast(ParamsDoc, raw)
    params = data["params"]
    names = [str(p["name"]) for p in params]
    part_param_count = sum(name.endswith(".p0") for name in names)
    part_count = len({name[-2:] for name in names if name.endswith((".p0", ".p1"))})
    routing_count = sum(
        name.startswith(("channel.", "low.", "high.", "level.", "delay."))
        for name in names
    )
    routing_base = len(params) - routing_count
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "/* GENERATED by plugin/tools/gen_params.py - do not edit. */",
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "",
        "struct P1ParamSpec {",
        "    int32_t engineId;",
        "    const char* id;",
        "    const char* name;",
        "    const char* unit;",
        "    const char* display;",
        "    int32_t min;",
        "    int32_t max;",
        "    int32_t def;",
        "    bool logarithmic;",
        "    bool modulatable;",
        "    bool audioRate;",
        "};",
        "",
        f"inline constexpr std::array<P1ParamSpec, {len(params)}> kP1ParamSpecs = {{{{",
    ]
    for p in params:
        row = (
            f"{p['id']}, "
            + c_string(p["name"])
            + ", "
            + c_string(display_name(p["name"]))
            + ", "
            + c_string(p["unit"])
            + ", "
            + c_string(p["display"])
            + ", "
            + f"{p['min']}, {p['max']}, {p['default']}, "
            + ("true" if p["curve"] == "log" else "false")
            + ", "
            + ("true" if p["modulatable"] else "false")
            + ", "
            + ("true" if p["rate"] == "sample" else "false")
        )
        lines.append("    {" + row + "},")
    lines += [
        "}};",
        f"inline constexpr int kP1ParamCount = {len(params)};",
        f"inline constexpr int kP1PartParamCount = {part_param_count};",
        f"inline constexpr int kP1PartCount = {part_count};",
        f"inline constexpr int kP1RoutingCount = {routing_count};",
        f"inline constexpr int kP1RoutingBase = {routing_base};",
        "",
    ]
    target.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
