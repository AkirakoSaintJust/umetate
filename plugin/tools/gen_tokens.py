"""Generate UiTokens.h from design/tokens.json.

The design tokens are the single source for colours, type sizes, metrics and
control geometry. The JUCE editor reads only this header.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import TypedDict, cast


class _TokenFile(TypedDict):
    colour: dict[str, str]
    size: dict[str, int]
    space: dict[str, int]
    control: dict[str, object]
    border: dict[str, object]


def _argb(hex_colour: str) -> int:
    value = hex_colour.lstrip("#")
    if len(value) != 6:
        raise ValueError(f"expected #rrggbb, got {hex_colour!r}")
    return 0xFF000000 | int(value, 16)


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: gen_tokens.py tokens.json UiTokens.h", file=sys.stderr)
        return 2
    source = Path(sys.argv[1])
    target = Path(sys.argv[2])
    raw = cast(object, json.loads(source.read_text(encoding="utf-8")))
    data = cast(_TokenFile, raw)
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "/* GENERATED by plugin/tools/gen_tokens.py - do not edit. */",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace p1::tokens {",
        "",
        "// colour, ARGB",
    ]
    for colour_name, colour_value in data["colour"].items():
        lines.append(
            f"inline constexpr std::uint32_t {colour_name} = "
            f"0x{_argb(colour_value):08x}u;"
        )

    lines += ["", "// type sizes, logical pixels"]
    for size_name, size_value in data["size"].items():
        token = size_name[0].upper() + size_name[1:]
        lines.append(f"inline constexpr float text{token} = {size_value}.0f;")

    lines += ["", "// layout"]
    for space_name, space_value in data["space"].items():
        lines.append(f"inline constexpr int {space_name} = {space_value};")

    lines += ["", "// control geometry"]
    for control_name, control_value in data["control"].items():
        if not isinstance(control_value, dict):
            lines.append(
                f"inline constexpr int {control_name} = "
                f"{int(cast(int, control_value))};"
            )
            continue
        control_dict = cast(dict[str, int], control_value)
        for field, number in control_dict.items():
            lines.append(f"inline constexpr int {control_name}_{field} = {number};")

    lines += ["", "// borders"]
    for border_name, border_value in data["border"].items():
        if isinstance(border_value, int):
            lines.append(f"inline constexpr int {border_name} = {border_value};")

    lines += ["", "} // namespace p1::tokens", ""]
    target.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
