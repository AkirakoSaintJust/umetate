"""Generate gen/math_tables.h, the const XIP fixed-point tables hal/fm1_math.h
serves. The output is deterministic, and it is checked in
(as gen/felucca_font.h).

Run from the firmware root:  python3 tools/gen_math_tables.py

Tables (all `const`, XIP):
  fm1_sin_q15[256]   quarter-sine, Q15, midpoint sampling (sin(pi/2*(i+.5)/256))
  fm1_exp2_q16[256]  exp2 decay 2^(-i/256), Q16  (envelopes / note-to-inc)
  fm1_log2_q16[256]  log2(1 + i/256), Q16        (log-domain FM)
  fm1_semi_q16[12]   2^(i/12), Q16, i=0..11      (tuning: semitone step)
  fm1_cent_q16[100]  2^(i/1200), Q16, i=0..99    (tuning: cent step)
"""

import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "gen" / "math_tables.h"


def q15(x: float) -> int:
    v = int(round(x * 32768.0))
    return max(-32768, min(32767, v))


def q16(x: float) -> int:
    v = int(round(x * 65536.0))
    return max(-2147483648, min(2147483647, v))


def c_array(ctype: str, name: str, values: list[int], width: int) -> list[str]:
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    row: list[str] = []
    for v in values:
        row.append(f"{v:>6d}")
        if len(row) == width:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return lines


def main() -> None:
    N = 256
    sin_q15 = [q15(math.sin(math.pi / 2.0 * i / N)) for i in range(N)]
    exp2_q16 = [q16(2.0 ** (-i / N)) for i in range(N)]
    log2_q16 = [q16(math.log2(1.0 + i / N)) for i in range(N)]
    semi_q16 = [q16(2.0 ** (i / 12.0)) for i in range(12)]
    cent_q16 = [q16(2.0 ** (i / 1200.0)) for i in range(100)]
    # Per-operator detune (the fm_op `detune` param, cents −50..+50) -> the Q15
    # pitch offset the phasor adds to `32768 + pitch` so the frequency shift is
    # *exact*: offset = 32768 · (2^(cents/1200) − 1), indexed `[cents + 50]`.
    detune_pitch = [
        round(32768.0 * (2.0 ** (d / 1200.0) - 1.0)) for d in range(-50, 51)
    ]

    # DX rate -> one-pole coefficient (Q16). Yamaha-style *non-uniform* curve: the
    # time constant is ~2^(sqrt(99-r) / 0.75) blocks, so the slow end has fine
    # granularity (each step ~5% faster) whilst "instant" is compressed to the very
    # top (rate 99 ≈ 0.73 ms). A uniform exponential (×2 per 8 steps) instead made
    # everything above ~64 read as "instant" and left 35 settings dead, whilst the
    # musical decay/release range (tens of ms .. ~1 s) stayed crowded below ~40. Rate
    # 0 ≈ 7 s (a long release), rate 50 ≈ 0.5 s, rate 64 ≈ 170 ms, rate 99 = instant.
    # Drives the dx_env / pitch_env stages.
    rate_coeff = [
        min(65536, max(0, round(65536.0 * 2.0 ** (-((99 - r) ** 0.5) / 0.75))))
        for r in range(100)
    ]
    # Yamaha total-level -> gain (Q15), 0.75 dB/step: 99 = 32767 (0 dB, maximum),
    # 50 ≈ −37 dB, 0 = silence. This is the OPM/OPP scale: the OPM `TL` register is
    # 0.75 dB per step, and the DX21/DX27/DX100 output level maps to it one step per
    # level (`TL = 99 - level`). It also makes the modulation index match those
    # synths: a level-75 modulator reaches π radians, rather than 4π. The operator
    # output level uses `fm1_level_gain[level] >> 2` for the −12 dB single-operator
    # headroom (four additive carriers then sum to 0 dBFS).
    level_gain = [0] + [
        max(1, min(32767, round(32767.0 * 10.0 ** (-(99 - l) * 0.75 / 20.0))))
        for l in range(1, 100)
    ]

    h = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * Copyright (C) 2026 P1Onken (umetate)",
        " * GENERATED by tools/gen_math_tables.py, do not edit by hand.",
        " * const XIP fixed-point tables for hal/fm1_math.h (docs/roadmap.md P2-3). */",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    h += c_array("int16_t", "fm1_sin_q15", sin_q15, 16)
    h += [""]
    h += c_array("int32_t", "fm1_exp2_q16", exp2_q16, 8)
    h += [""]
    h += c_array("int32_t", "fm1_log2_q16", log2_q16, 8)
    h += [""]
    h += c_array("int32_t", "fm1_semi_q16", semi_q16, 8)
    h += [""]
    h += c_array("int32_t", "fm1_cent_q16", cent_q16, 8)
    h += [""]
    h += c_array("int32_t", "fm1_detune_pitch", detune_pitch, 8)
    h += [""]
    h += c_array("int32_t", "fm1_rate_coeff", rate_coeff, 8)
    h += [""]
    h += c_array("int32_t", "fm1_level_gain", level_gain, 8)
    h += [""]

    OUT.write_text("\n".join(h) + "\n")
    print(f"wrote {OUT} ({len(sin_q15)}-entry sin/exp/log tables)")


if __name__ == "__main__":
    main()
