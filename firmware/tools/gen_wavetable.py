"""Generate gen/wavetable.h — the 12-waveform OPZ+OPL union as a single Q15 table.

Replaces fm1_sin_wave's per-sample switch: every waveform is precomputed into
`fm1_wave[12 * 1024]` (12 waves x 1024 samples, Q15), indexed by
`(waveform << 10) | (phase >> 22)` — so the per-sample oscillator is one load and
the waveform selection is a block-rate base (the oscillator node's block_derived).
Deterministic; the output is checked in (as gen/math_tables.h).

Run from the firmware root:  python3 tools/gen_wavetable.py
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "gen" / "wavetable.h"
N_WAVES = 12
N = 1024  # samples per wave (10-bit phase index, matching fm1_sin's resolution)


def q15(x: float) -> int:
    v = int(round(x * 32768.0))
    return max(-32768, min(32767, v))


# the quarter sine, identical to gen_math_tables.py's fm1_sin_q15
SIN = [q15(math.sin(math.pi / 2.0 * i / 256)) for i in range(256)]


def fm1_sin(phase: int) -> int:
    q = (phase >> 30) & 3
    i = (phase >> 22) & 255
    v = SIN[255 - i] if (q & 1) else SIN[i]
    return -v if (q & 2) else v


def q15_mul(a: int, b: int) -> int:
    return (a * b + (1 << 14)) >> 15


def sin_wave(phase: int, ws: int) -> int:
    """The exact C fm1_sin_wave(phase, ws) as a pure function of the top 10 bits."""
    s = fm1_sin(phase)
    a = -s if s < 0 else s
    half = (phase >> 31) & 1
    q = (phase >> 30) & 3
    if ws == 0:
        return s
    if ws == 1:
        return q15_mul(s, a)                      # triangle (sin . |sin|)
    if ws == 2:
        return 0 if half else a                  # half sine
    if ws == 3:
        return 0 if half else q15_mul(s, a)      # half triangle
    if ws == 4:
        return 0 if half else fm1_sin((phase << 1) & 0xFFFFFFFF)   # double sine
    if ws == 5:
        s2 = fm1_sin((phase << 1) & 0xFFFFFFFF)
        return 0 if half else q15_mul(s2, -s2 if s2 < 0 else s2)   # double triangle
    if ws == 6:
        s2 = fm1_sin((phase << 1) & 0xFFFFFFFF)
        return 0 if half else (-s2 if s2 < 0 else s2)              # double half sine
    if ws == 7:
        s2 = fm1_sin((phase << 1) & 0xFFFFFFFF)
        return 0 if half else q15_mul(s2, s2)     # double half triangle (sin^2)
    if ws == 8:
        return a                                  # rectified |sin|
    if ws == 9:
        return 0 if (q & 1) else a                # pulse (half-rectified)
    if ws == 10:
        return -32767 if half else 32767          # square
    if ws == 11:
        return (phase >> 16) - 32768              # saw
    return s


def c_array(name: str, values: list[int]) -> list[str]:
    lines = [f"static const int16_t {name}[{len(values)}] = {{"]
    row: list[str] = []
    for v in values:
        row.append(f"{v:>6d}")
        if len(row) == 16:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return lines


def main() -> None:
    wave: list[int] = []
    for ws in range(N_WAVES):
        for p in range(N):
            wave.append(sin_wave(p << 22, ws))

    h = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * Copyright (C) 2026 P1Onken (umetate)",
        " * GENERATED by tools/gen_wavetable.py — do not edit by hand.",
        " * The 12-waveform OPZ (YM2414) + OPL (YM3812) union, Q15, 1024 samples each.",
        " * Indexed by (waveform << 10) | (phase >> 22); the waveform base is a",
        " * block-rate value (the oscillator node's block_derived). */",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    h += c_array("fm1_wave", wave)
    OUT.write_text("\n".join(h) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(wave)} samples)")


if __name__ == "__main__":
    main()
