"""Generate gen/naive_wave.h — the classic oscillator shapes as a single Q15 table.

`fm1_naive_wave[4 * 1024]` — saw, sine, triangle, square — indexed by
`(shape << 10) | (phase >> 22)`. These are naive (non-band-limited) tables, so they
alias at high pitches (by design — the polyBLEP `saw` node is the band-limited
option). The pulse/square width is *not* a table: it is the `phase_dist` node's `d`
bend applied before this read (PWM). Deterministic; the output is checked in (like
gen/wavetable.h).

Run from the firmware root:  python3 tools/gen_naive_wave.py
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "gen" / "naive_wave.h"
N_SHAPES = 4
N = 1024  # samples per shape (10-bit phase index, matching fm1_sin's resolution)


def q15(x: float) -> int:
    v = int(round(x * 32768.0))
    return max(-32768, min(32767, v))


# the quarter sine, identical to gen_math_tables.py's fm1_sin_q15
SIN = [q15(math.sin(math.pi / 2.0 * i / 256)) for i in range(256)]


def fm1_sin(phase: int) -> int:
    q = (phase >> 30) & 3
    i = (phase >> 22) & 255
    v = SIN[255 - i] if (q & 1) else SIN[i]
    return -v if (q & 2) else v


def shape_value(shape: int, i: int) -> int:
    """The C `fm1_naive_wave[(shape<<10)|i]` value, exactly."""
    if shape == 0:   # saw: linear ramp -1 -> +1
        return (i << 6) - 32768
    if shape == 1:   # sine (the quarter table, matching fm1_sin)
        return fm1_sin(i << 22)
    if shape == 2:   # triangle: linear -1 -> +1 -> -1
        return q15(1.0 - 4.0 * abs(i / 1024.0 - 0.5))
    if shape == 3:   # square: 50% duty (width comes from phase_dist PWM)
        return -32767 if i >= 512 else 32767
    return 0


def c_array(name: str, values: list[int]) -> list[str]:
    lines = [f"static const int16_t {name}[{len(values)}] = {{"]
    row: list[str] = []
    for v in values:
        row.append(f"{v:>6d}")
        if len(row) == 16:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return lines


def main() -> None:
    wave: list[int] = []
    for shape in range(N_SHAPES):
        for i in range(N):
            wave.append(shape_value(shape, i))

    h = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * Copyright (C) 2026 P1Onken (umetate)",
        " * GENERATED by tools/gen_naive_wave.py — do not edit by hand.",
        " * The naive (non-band-limited) oscillator shapes, Q15, 1024 samples each:",
        " *   0 = saw, 1 = sine, 2 = triangle, 3 = square.",
        " * Indexed by (shape << 10) | (phase >> 22); the shape base is a block-rate",
        " * value. Pulse width is phase_dist's `d` bend (PWM) before this read. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    h += c_array("fm1_naive_wave", wave)
    OUT.write_text("\n".join(h) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(wave)} samples)")


if __name__ == "__main__":
    main()
