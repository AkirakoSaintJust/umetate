"""Generate gen/naive_wave.h — the classic oscillator shapes, band-limited for
saw/square.

`fm1_naive_wave` holds, contiguously:
  - shapes 1 (sine) and 2 (triangle): one 1024-sample table each (already
    band-limited by construction);
  - shapes 0 (saw) and 3 (square): MIP=6 band-limited tables each (harmonic
    counts 32..1) — the same anti-aliasing fix as the operators' `osc`, so the
    naive oscillator's saw/square stop aliasing at high pitches. Each is an
    additive (truncated-Fourier) synthesis of the naive shape.

`fm1_naive_base[4]` gives each shape's mip-0 offset (in 1024-sample units); a
reader adds `mip << 10` for shapes 0/3. Total 14336 samples.

Pulse/square *width* is not a table: it is the `phase_dist` node's `d` bend
applied before this read (PWM). Deterministic; the output is checked in.

Run from the firmware root:  python3 tools/gen_naive_wave.py
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "gen" / "naive_wave.h"
N_SHAPES = 4
N = 1024  # samples per shape (10-bit phase index, matching fm1_sin's resolution)
MIP = 6  # band-limited mip levels for saw/square
BL_SHAPES = (0, 3)  # saw, square


def q15(x: float) -> int:
    v = int(round(x * 32768.0))
    return max(-32768, min(32767, v))


def clamp15(x: float) -> int:
    v = int(round(x))
    return max(-32768, min(32767, v))


# the quarter sine, identical to gen_math_tables.py's fm1_sin_q15
SIN = [q15(math.sin(math.pi / 2.0 * i / 256)) for i in range(256)]


def fm1_sin(phase: int) -> int:
    q = (phase >> 30) & 3
    i = (phase >> 22) & 255
    v = SIN[255 - i] if (q & 1) else SIN[i]
    return -v if (q & 2) else v


def shape_value(shape: int, i: int) -> int:
    """The C `fm1_naive_wave[(shape<<10)|i]` value, exactly."""
    if shape == 0:   # saw: linear ramp -1 -> +1
        return (i << 6) - 32768
    if shape == 1:   # sine (the quarter table, matching fm1_sin)
        return fm1_sin(i << 22)
    if shape == 2:   # triangle: linear -1 -> +1 -> -1
        return q15(1.0 - 4.0 * abs(i / 1024.0 - 0.5))
    if shape == 3:   # square: 50% duty (width comes from phase_dist PWM)
        return -32767 if i >= 512 else 32767
    return 0


def band_limited(shape: int, harm: int) -> list[int]:
    """The band-limited Q15 table for `shape`, harmonics 1..harm (truncated Fourier
    / offline IFFT), projected from the exact naive shape with a DFT."""
    a = [0.0] * (harm + 1)
    b = [0.0] * (harm + 1)
    for k in range(harm + 1):
        sa = sb = 0.0
        for i in range(N):
            ang = 2.0 * math.pi * k * i / N
            v = shape_value(shape, i)
            sa += v * math.cos(ang)
            sb += v * math.sin(ang)
        a[k] = sa * 2.0 / N
        b[k] = sb * 2.0 / N
    out: list[int] = []
    for i in range(N):
        ang = 2.0 * math.pi * i / N
        total = a[0] * 0.5
        for k in range(1, harm + 1):
            total += a[k] * math.cos(k * ang) + b[k] * math.sin(k * ang)
        out.append(clamp15(total))
    return out


def c_array(name: str, ctype: str, values: list[int]) -> list[str]:
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    row: list[str] = []
    for v in values:
        row.append(f"{v:>6d}")
        if len(row) == 16:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return lines


def main() -> None:
    wave: list[int] = []
    base: list[int] = []
    for shape in range(N_SHAPES):
        base.append(len(wave) // N)  # the mip-0 offset (units of N samples)
        if shape in BL_SHAPES:
            for mip in range(MIP):
                wave.extend(band_limited(shape, 1 << (MIP - 1 - mip)))
        else:
            for i in range(N):
                wave.append(shape_value(shape, i))

    h = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * Copyright (C) 2026 P1Onken (umetate)",
        " * GENERATED by tools/gen_naive_wave.py — do not edit by hand.",
        " * The classic oscillator shapes, Q15.",
        " * Shapes 1 (sine) and 2 (triangle) are one 1024-sample table each; shapes",
        " * 0 (saw) and 3 (square) are MIP=6 band-limited tables (harmonic counts",
        " * 32..1) for top-octave anti-aliasing. `fm1_naive_base[shape]` is shape's",
        " * mip-0 offset in 1024-sample units; the per-sample index is",
        " *   fm1_naive_wave[(fm1_naive_base[shape] + mip) << 10 | (phase >> 22)].",
        " * Pulse width is phase_dist's `d` bend (PWM) before this read. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    h += c_array("fm1_naive_wave", "int16_t", wave)
    h += [""]
    h += c_array("fm1_naive_base", "uint8_t", base)
    OUT.write_text("\n".join(h) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(wave)} samples, {len(base)} shape bases)")


if __name__ == "__main__":
    main()
