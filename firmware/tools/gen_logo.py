"""Generate gen/logo.h, the boot-splash logo, run-length encoded RGB565.

Reads `firmware/assets/umetate240.png` (240x240, the umetate wordmark set in the
"Digital Desolation Plus" typeface, see
`firmware/assets/Digital-Desolation-Plus-LICENSE.txt`) and emits a row-major RLE
stream of *byte-swapped* RGB565 pixels: a run is a `count` word (1..65535) then a
`colour` word, and the stream ends with a zero count. The byte swap matches
gfx.c's canvas convention (the ST7789 takes big-endian RGB565), so `logo_draw()`
blits the decoded rows straight out.

Deterministic; the output is checked in (like gen/wavetable.h). Run from the
firmware root:

    python3 tools/gen_logo.py
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image

_SRC = Path(__file__).resolve().parents[1] / "assets" / "umetate240.png"
_OUT = Path(__file__).resolve().parents[1] / "gen" / "logo.h"
_W = 240
_H = 240


def _rgb565(rgb: tuple[int, int, int]) -> int:
    r, g, b = rgb
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def _swap16(v: int) -> int:
    return ((v >> 8) & 0xFF) | ((v & 0xFF) << 8)


def _rle(px: list[int]) -> list[tuple[int, int]]:
    """Row-major run-length encode: (count, colour) runs over the flat pixels."""
    runs: list[tuple[int, int]] = []
    prev: int | None = None
    count = 0
    for v in px:
        if v == prev:
            count += 1
        else:
            if prev is not None:
                runs.append((count, prev))
            prev = v
            count = 1
    if prev is not None:
        runs.append((count, prev))
    return runs


def _decode(runs: list[tuple[int, int]]) -> list[int]:
    out: list[int] = []
    for count, colour in runs:
        out.extend([colour] * count)
    return out


def main() -> None:
    im = Image.open(_SRC).convert("RGB")
    if im.size != (_W, _H):
        raise SystemExit(f"{_SRC}: want {_W}x{_H}, got {im.size}")
    data = im.tobytes()
    px = [
        _swap16(_rgb565((data[i], data[i + 1], data[i + 2])))
        for i in range(0, len(data), 3)
    ]
    runs = _rle(px)
    if _decode(runs) != px:
        raise SystemExit("RLE round-trip mismatch")

    words: list[int] = []
    for count, colour in runs:
        words.append(count)
        words.append(colour)
    words.append(0)  # terminator

    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * Copyright (C) 2026 P1Onken (umetate)",
        " * GENERATED by tools/gen_logo.py, do not edit by hand.",
        " * The boot-splash logo (firmware/assets/umetate240.png, 240x240), a",
        " * row-major RLE stream of byte-swapped RGB565: a run is `count` (1..65535)",
        " * then `colour`, terminated by a zero count. Byte-swapped to match gfx.c",
        " * big-endian RGB565), so logo_draw() blits it straight out. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define LOGO_W {_W}u",
        f"#define LOGO_H {_H}u",
        "",
        f"static const uint16_t LOGO_RLE[{len(words)}] = {{",
    ]
    row: list[str] = []
    for v in words:
        row.append(f"{v:>6d}")
        if len(row) == 12:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")

    _OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {_OUT} ({len(runs)} runs, {len(words)} words)")


if __name__ == "__main__":
    main()
