_TABLE_RE = re.compile(r"\$\{table\.([^}]*)\}")


def emit(graph: CompiledGraph) -> str:
    """Render a CompiledGraph into the generated `<synth>_dsp.c`."""
    by_id = {i.id: i for i in graph.instances}
    table_names = {t.name for t in graph.tables}
    lines: list[str] = []
    lines.append(
        f"/* GENERATED by umetate — do not edit. name={graph.name} voices={graph.voices} */"
    )
    lines.append('#include "fm1_math.h"')
    lines.append('#include "fm1_ipc.h"')
    if graph.tables:
        lines.append('#include "tables.h"')
    lines.append("")
    lines.append("#ifndef UMETATE_CPU1")
    lines.append("#define UMETATE_CPU1")
    lines.append("#endif")
    lines.append("#ifndef UMETATE_POOL")
    lines.append("#define UMETATE_POOL")
    lines.append("#endif")
    lines.append("")
    lines.append("#if defined(UMETATE_TARGET_DSP)")
    lines.append(
        '#define UMETATE_DSP_API __attribute__((section(".dsp_text"), noinline, used))'
    )
    lines.append("#else")
    lines.append("#define UMETATE_DSP_API")
    lines.append("#endif")
    lines.append("")
    lines.append(f"#define NVOICE {graph.voices}")
    lines.append(f"#define N_PART {graph.n_parts}")
    lines.append(f"#define CONTROL_BLOCK {graph.control_block}")
    lines.append("")
    per_part = graph.n_parts > 1
    lines.extend(_note_to_inc())
    lines.extend(_state_decls(graph))
    lines.extend(_voice.voice_state_decls(per_part))
    lines.extend(_voice.mode_param_decls(graph.n_parts))
    lines.extend(_routing_decls(graph))
    lines.append("static uint32_t patch_gate UMETATE_CPU1;")
    lines.extend(_param_decls(graph))
    lines.extend(_param_tables(graph))
    lines.append("")
    lines.extend(_voice.helpers(per_part))  # voice_mono_active (used by note_on/off)
    lines.extend(_note_derived_fn(graph))  # <name>_note_derived (render + seam)
    lines.extend(_render(graph, by_id, table_names))
    lines.extend(_seam(graph, by_id))
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ state ----


def _state_ctype(kind: str) -> str:
    """The C type for a state field (phase/q32 wrap as unsigned)."""
    if kind in ("q12", "q15", "q16", "int16", "int32"):
        return "int32_t"
    if kind in ("q32", "phase", "uint32"):
        return "uint32_t"
    return "uint32_t"


def _state_decls(graph: CompiledGraph) -> list[str]:
    """Emit SoA (voice) / scalar (global) state and pool ring buffers."""
    lines: list[str] = []
    for i in graph.instances:
        for sname, kind in i.spec.state.items():
            if kind == POOL:
                lines.append(f"#define {i.c}_{sname}_len 8192")
                lines.append(f"#define {i.c}_delay_mask 8191")
                lines.append(
                    f"static int16_t {i.c}_{sname}[{i.c}_{sname}_len] UMETATE_POOL;"
                )
            elif i.zone == "voice":
                lines.append(
                    f"static {_state_ctype(kind)} {i.c}_{sname}[NVOICE] UMETATE_CPU1;"
                )
            else:
                lines.append(f"static {_state_ctype(kind)} {i.c}_{sname} UMETATE_CPU1;")
    return lines


def _routing_decls(graph: CompiledGraph) -> list[str]:
    """The per-part routing backing arrays (`part_channel`/`part_low`/`part_high`/
    `part_level`/`part_delay`), initialized from the routing params' defaults."""
    if graph.n_parts <= 1:
        return []
    defaults: dict[str, list[int]] = {}
    for p in graph.params:
        if p.part is not None and p.cname.startswith("part_"):
            defaults.setdefault(p.cname, []).append(p.default)
    lines: list[str] = []
    for cname, vals in defaults.items():
        lines.append(
            f"static int32_t {cname}[{graph.n_parts}] = {{ "
            f"{', '.join(str(v) for v in vals)} }};"
        )
    return lines


def _param_decls(graph: CompiledGraph) -> list[str]:
    """Emit one `static int32_t` (or a `[N_PART]` array) per node param, per-part
    for the voice zone, initialized to its default/value."""
    lines: list[str] = []
    per_part = graph.n_parts > 1
    for i in graph.instances:
        for pname, kind in i.spec.params.items():
            default = param_default(
                kind, i.params.get(pname) or i.spec.param_defaults.get(pname)
            )
            if per_part and i.zone == "voice":
                init = ", ".join(str(default) for _ in range(graph.n_parts))
                lines.append(
                    f"static int32_t {i.param_expr(pname)}[{graph.n_parts}] = {{ {init} }};"
                )
            else:
                lines.append(f"static int32_t {i.param_expr(pname)} = {default};")
    return lines


def _slot_ref(p: ParamEntry) -> str:
    """The `&backing` (or `&backing[part]`) expression for a param's slot."""
    return f"&{p.cname}[{p.part}]" if p.part is not None else f"&{p.cname}"


def _param_tables(graph: CompiledGraph) -> list[str]:
    """The param slot table + the `dsp_param` metadata table (both `const`, XIP)."""
    params = graph.params
    slots = ", ".join(_slot_ref(p) for p in params) if params else "0"
    lines = [
        f"#define PARAM_COUNT {len(params)}",
        f"static int32_t *const synth_param_slots[{len(params) or 1}] = {{ {slots} }};",
        "",
        "typedef struct { uint32_t id; const char *name; int32_t min, max, def;",
        "                 uint8_t curve; uint8_t rate; const char *unit; } dsp_param;",
        f"const dsp_param {graph.name}_dsp_params[{len(params) or 1}] = {{",
    ]
    if not params:
        lines.append('    { 0, "", 0, 0, 0, 0, 0, 0 },')
    else:
        for p in params:
            curve = 1 if p.curve == "log" else 0
            rate = 1 if p.rate == "sample" else 0
            name = p.name.replace("\\", "\\\\").replace('"', '\\"')
            unit = p.unit.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(
                f'    {{ {p.id}u, "{name}", {p.min}, {p.max}, {p.default}, '
                f'{curve}u, {rate}u, "{unit}" }},'
            )
    lines.append("};")
    return lines


# ----------------------------------------------------------------- render ----


def _tap_clear_fn(name: str) -> list[str]:
    """The per-block zero of the tap buffers (one pass before the block loop, so
    `render_voices_block`'s `fm1_sat_add32` accumulation starts from silence)."""
    return [
        f"static inline __attribute__((always_inline)) void {name}_taps_clear(",
        "        int32_t (*taps)[UMETATE_DSP_BLOCK_FRAMES]) {",
        "    for (uint32_t k = 0; k < N_TAP_CH; k++)",
        "        for (uint32_t f = 0; f < UMETATE_DSP_BLOCK_FRAMES; f++)",
        "            taps[k][f] = 0;",
        "}",
        "",
    ]


def _render(
    graph: CompiledGraph, by_id: dict[str, NodeInstance], table_names: set[str]
) -> list[str]:
    voice_audio = _zone(graph.voice_order, by_id, audio_only=True)
    voice_ctrl = _zone(graph.voice_order, by_id, audio_only=False)
    global_audio = _zone(graph.global_order, by_id, audio_only=True)
    global_ctrl = _zone(graph.global_order, by_id, audio_only=False)

    lines: list[str] = []

    # Split-core render (docs/roadmap.md §4.2, D3): the hot per-voice loop is a
    # separable phase `render_voices_block` (one CONTROL_BLOCK's worth of voice
    # synthesis into a caller bus), so it can later run on both cores. `dsp_render`
    # keeps the block loop and does the global control prologue + global audio
    # (filter/wavefolder) inline — those stay single-core. The global control-rate
    # outputs are file-scope temps: `dsp_render` writes them each block, and
    # `render_voices_block` reads them.
    for i in _control_rate_nodes(graph, by_id):
        for port in i.spec.outs:
            if i.zone == "voice":
                lines.append(f"static int32_t {i.c}_{port}_x[NVOICE] UMETATE_CPU1;")
            else:
                lines.append(f"static int32_t {i.c}_{port}_x UMETATE_CPU1;")
    lines.append(
        f"static int32_t {graph.name}_render_bus0[CONTROL_BLOCK] UMETATE_CPU1;"
    )
    lines.append(
        f"static int32_t {graph.name}_render_bus1[CONTROL_BLOCK] UMETATE_CPU1;"
    )
    if graph.taps:
        n_ch = len(graph.taps) * graph.n_parts
        lines.append(f"#define N_TAP {len(graph.taps)}u")
        lines.append(f"#define N_TAP_CH {n_ch}u")
        lines.append(
            f"static int32_t {graph.name}_tap0[N_TAP_CH][UMETATE_DSP_BLOCK_FRAMES] UMETATE_CPU1;"
        )
        lines.append(
            f"static int32_t {graph.name}_tap1[N_TAP_CH][UMETATE_DSP_BLOCK_FRAMES] UMETATE_CPU1;"
        )
        lines.extend(_tap_clear_fn(graph.name))
    lines.append("")

    lines.extend(_render_pre_block(graph, by_id, table_names, global_ctrl))
    lines.extend(
        _render_voices_block(graph, by_id, table_names, voice_ctrl, voice_audio)
    )
    lines.extend(_render_post_block(graph, by_id, table_names, global_audio))
    lines.extend(_render_dsp_render(graph))
    lines.extend(_render_split(graph))
    return lines


def _dedent4(lines: list[str]) -> list[str]:
    """De-indent block-loop-level lines (8-space base) to a per-block function body."""
    return [line[4:] if line.startswith("    ") else line for line in lines]


def _render_pre_block(
    graph: CompiledGraph,
    by_id: dict[str, NodeInstance],
    table_names: set[str],
    global_ctrl: list[NodeInstance],
) -> list[str]:
    """One CONTROL_BLOCK's global control prologue (single core): the delay
    countdown, patch gate, global control-rate nodes, and the portamento glide —
    writing the file-scope temps that `render_voices_block` reads."""
    name = graph.name
    per_part = graph.n_parts > 1
    lines = [f"UMETATE_DSP_API void {name}_render_pre_block(void) {{"]
    if per_part:
        lines.extend(_dedent4(_voice.delay_countdown(name)))
    lines.extend(
        _dedent4(
            [
                "        patch_gate = 0u;",
                "        for (uint32_t _pg = 0; _pg < NVOICE; _pg++)",
                "            if (voice_gate[_pg]) { patch_gate = 1u; break; }",
            ]
        )
    )
    for i in global_ctrl:
        lines.extend(_dedent4(_emit_body(i, "0", "        ", table_names, per_part)))
    # global block-derived state (e.g. a modulatable param's effective value),
    # after the control prologue so its control inputs are available
    gblock = [by_id[iid] for iid in graph.global_order if by_id[iid].block_derived]
    for i in gblock:
        for field, template in i.block_derived.items():
            expr = substitute(i, template, "0", table_names, per_part)
            lines.append(f"    {i.state_ref(field, '0')} = {expr};")
    lines.extend(_dedent4(_voice.glide(name, graph.n_parts > 1)))
    lines.append("}")
    lines.append("")
    return lines


def _render_post_block(
    graph: CompiledGraph,
    by_id: dict[str, NodeInstance],
    table_names: set[str],
    global_audio: list[NodeInstance],
) -> list[str]:
    """One CONTROL_BLOCK's global audio post (single core): the filter/wavefolder
    over the (already combined) bus `src`, then the output write."""
    name, cb = graph.name, graph.control_block
    per_part = graph.n_parts > 1
    lines = [
        f"UMETATE_DSP_API void {name}_render_post_block(int32_t *out, const int32_t *src, uint32_t b, uint32_t frames) {{",
        f"    for (uint32_t f = b; f < b + {cb}u && f < frames; f++) {{",
        "        int32_t bus = src[f - b];",
    ]
    for i in global_audio:
        lines.extend(_emit_body(i, "0", "        ", table_names, per_part))
    out_expr = _final_out(graph, by_id)
    lines.append(f"        out[f * 2] = {out_expr}; out[f * 2 + 1] = {out_expr};")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return lines


def _render_voices_block(
    graph: CompiledGraph,
    by_id: dict[str, NodeInstance],
    table_names: set[str],
    voice_ctrl: list[NodeInstance],
    voice_audio: list[NodeInstance],
) -> list[str]:
    """One CONTROL_BLOCK of voice synthesis for voices [v0, v1) into `bus` (a
    caller buffer of CONTROL_BLOCK samples). Reads the file-scope global control
    temps written by `dsp_render`'s prologue for this block."""
    name, cb = graph.name, graph.control_block
    per_part = graph.n_parts > 1
    taps = graph.taps
    sig = (
        f"UMETATE_DSP_API void {name}_render_voices_block(int32_t *bus, "
        + ("int32_t (*taps)[UMETATE_DSP_BLOCK_FRAMES], " if taps else "")
        + "uint32_t v0, uint32_t v1, uint32_t b, uint32_t frames) {"
    )
    lines = [sig]

    # release-tail countdown: a released (gate=0) voice stays allocated until its
    # envelope finishes releasing; decrement its remaining hold once per block.
    lines.append("    for (uint32_t v = v0; v < v1; v++) {")
    lines.append("        if (!voice_gate[v] && voice_rel[v] > 0u) voice_rel[v]--;")
    lines.append("    }")

    # control prologue: voice control-rate nodes (per voice, this core's range)
    if voice_ctrl:
        lines.append("    for (uint32_t v = v0; v < v1; v++) {")
        lines.append("        if (!voice_gate[v] && !voice_rel[v]) continue;")
        for i in voice_ctrl:
            lines.extend(_emit_body(i, "v", "        ", table_names, per_part))
        lines.append(
            "        voice_trig[v] = 0; /* one-shot note-on edge, consumed above */"
        )
        lines.append("    }")

    # block-derived state: recompute per-voice block-constant values after the
    # global control temps are available (e.g. the phasor's pitch-scaled
    # increment `inc * (32768 + pitch) >> 15` — pitch is control-rate, so the
    # multiply was being redone every sample).
    block_derived = [
        by_id[iid] for iid in graph.voice_order if by_id[iid].block_derived
    ]
    if block_derived:
        lines.append("    for (uint32_t v = v0; v < v1; v++) {")
        lines.append("        if (!voice_gate[v] && !voice_rel[v]) continue;")
        for i in block_derived:
            for field, template in i.block_derived.items():
                expr = substitute(i, template, "v", table_names, per_part)
                lines.append(f"        {i.state_ref(field, 'v')} = {expr};")
        lines.append("    }")

    # audio loop
    lines.append(f"    for (uint32_t f = b; f < b + {cb}u && f < frames; f++) {{")
    lines.append("        bus[f - b] = 0;")
    lines.append("        for (uint32_t v = v0; v < v1; v++) {")
    lines.append("            if (!voice_gate[v] && !voice_rel[v]) continue;")

    breakers = [i for i in voice_audio if i.is_breaker()]
    normal = [i for i in voice_audio if not i.is_breaker()]
    for i in breakers:
        read, _ = _split_template(i.spec.body)
        lines.extend(_emit_lines(read, i, "v", "            ", table_names, per_part))
    for i in normal:
        lines.extend(_emit_body(i, "v", "            ", table_names, per_part))

    mix_expr = _voice_mix(graph, by_id, normal)
    if mix_expr is not None:
        if per_part:
            lines.append(
                f"            bus[f - b] = fm1_sat_add32(bus[f - b], "
                f"fm1_q15_mul({mix_expr}, fm1_level_gain[part_level[voice_part[v]]]));"
            )
        else:
            lines.append(
                f"            bus[f - b] = fm1_sat_add32(bus[f - b], {mix_expr});"
            )

    if taps:
        # per-op scope taps (§6.11.4 L11): accumulate each tap source's output
        # local, per part (so the HOME 4-op scope shows the active part's ops).
        # `f < UMETATE_DSP_BLOCK_FRAMES` bounds the tap window to one block (the
        # scope snapshot); host tests render larger `frames` than the target.
        lines.append("            if (f < UMETATE_DSP_BLOCK_FRAMES) {")
        if per_part:
            lines.append("                uint32_t _tp = voice_part[v];")
            for k, t in enumerate(taps):
                expr = by_id[t.node].out_local(t.port)
                idx = f"{k} * {graph.n_parts} + _tp"
                lines.append(
                    f"                taps[{idx}][f] = fm1_sat_add32(taps[{idx}][f], "
                    f"fm1_q15_mul({expr}, fm1_level_gain[part_level[_tp]]));"
                )
        else:
            for k, t in enumerate(taps):
                expr = by_id[t.node].out_local(t.port)
                lines.append(
                    f"                taps[{k}][f] = fm1_sat_add32(taps[{k}][f], {expr});"
                )
        lines.append("            }")

    for i in breakers:
        _, write = _split_template(i.spec.body)
        lines.extend(_emit_lines(write, i, "v", "            ", table_names, per_part))
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return lines


def _render_dsp_render(graph: CompiledGraph) -> list[str]:
    """The single-core block loop: pre → voices([0, NVOICE)) → post. This is the
    reference path (host tests + CPU0-only fallback)."""
    name, cb = graph.name, graph.control_block
    if graph.taps:
        return [
            f"UMETATE_DSP_API void {name}_dsp_render(int32_t *out, uint32_t frames) {{",
            f"    {name}_taps_clear({name}_tap0);",
            f"    for ({_CONTROL_BLOCK_TYPE} b = 0; b < frames; b += {cb}u) {{",
            f"        {name}_render_pre_block();",
            f"        {name}_render_voices_block({name}_render_bus0, {name}_tap0, 0u, NVOICE, b, frames);",
            f"        {name}_render_post_block(out, {name}_render_bus0, b, frames);",
            "    }",
            "}",
            "",
        ]
    return [
        f"UMETATE_DSP_API void {name}_dsp_render(int32_t *out, uint32_t frames) {{",
        f"    for ({_CONTROL_BLOCK_TYPE} b = 0; b < frames; b += {cb}u) {{",
        f"        {name}_render_pre_block();",
        f"        {name}_render_voices_block({name}_render_bus0, 0u, NVOICE, b, frames);",
        f"        {name}_render_post_block(out, {name}_render_bus0, b, frames);",
        "    }",
        "}",
        "",
    ]


def _render_split(graph: CompiledGraph) -> list[str]:
    """The split-core dispatch (target only): per block, the pre on CPU0, then CPU0
    renders [0, N0) while CPU1 renders [N0, NVOICE) via the mailbox; CPU1 then
    waits for CPU0's bus, combines, and runs the post — so the heavier post (filters
    + wavefolder) lands on the cooler core. `N0` is the patch's `cpu0_voices`
    (default `voices//2`). Falls back to CPU0-only when core 1 is off or gave up
    (`fm1_cpu1_wait` returns non-zero and holds core 1)."""
    name, cb = graph.name, graph.control_block
    n0 = graph.cpu0_voices if graph.cpu0_voices >= 0 else graph.voices // 2
    has_taps = bool(graph.taps)
    taps_field = "int32_t (*taps)[UMETATE_DSP_BLOCK_FRAMES]; " if has_taps else ""
    tap_arg = f", {name}_tap0" if has_taps else ""
    tap_arg1 = f", {name}_tap1" if has_taps else ""
    job_tap_arg = f", {name}_render_job.taps" if has_taps else ""
    lines = [
        "#if FM1_CPU1_USED",
        f"typedef struct {{ int32_t *bus; int32_t *bus0; int32_t *out; {taps_field}uint32_t v0, v1, b, frames; }} {name}_render_job_t;",
        f"static {name}_render_job_t {name}_render_job;",
        f"static volatile uint32_t {name}_render_bus0_ready;",
        # CPU1's job: render its voice half, wait for CPU0's bus, combine, then post.
        f"static void {name}_render_post_job(uint32_t arg) {{",
        "    (void)arg;",
        f"    {name}_render_voices_block({name}_render_job.bus{job_tap_arg}, {name}_render_job.v0,",
        f"        {name}_render_job.v1, {name}_render_job.b, {name}_render_job.frames);",
        # acquire CPU0's bus: spin on the flag, then csync once *after* observing
        # it set (the codebase's read-flag -> csync -> use-data ordering, as in
        # dsp_cmd_pop and fm1_c1_main), so CPU0's bus0 writes are visible below.
        f"    while (!{name}_render_bus0_ready) {{ }}",
        "    FM1_CSYNC();",
        f"    for (uint32_t f = {name}_render_job.b; f < {name}_render_job.b + {cb}u && f < {name}_render_job.frames; f++)",
        f"        {name}_render_job.bus0[f - {name}_render_job.b] = fm1_sat_add32({name}_render_job.bus0[f - {name}_render_job.b], {name}_render_job.bus[f - {name}_render_job.b]);",
        f"    {name}_render_post_block({name}_render_job.out, {name}_render_job.bus0, {name}_render_job.b, {name}_render_job.frames);",
        "}",
        f"void {name}_render_split(int32_t *out, uint32_t frames) {{",
    ]
    if has_taps:
        lines.append(f"    {name}_taps_clear({name}_tap0);")
        lines.append(f"    {name}_taps_clear({name}_tap1);")
    lines.append(f"    for ({_CONTROL_BLOCK_TYPE} b = 0; b < frames; b += {cb}u) {{")
    lines.append("        int dispatched;")
    lines.append(f"        {name}_render_pre_block();")
    lines.append(f"        {name}_render_bus0_ready = 0;")
    lines.append(f"        {name}_render_job.bus = {name}_render_bus1;")
    lines.append(f"        {name}_render_job.bus0 = {name}_render_bus0;")
    lines.append(f"        {name}_render_job.out = out;")
    if has_taps:
        lines.append(f"        {name}_render_job.taps = {name}_tap1;")
    lines.append(
        f"        {name}_render_job.v0 = {n0}u; {name}_render_job.v1 = NVOICE;"
    )
    lines.append(f"        {name}_render_job.b = b; {name}_render_job.frames = frames;")
    lines.append(f"        dispatched = fm1_cpu1_dispatch({name}_render_post_job, 0u);")
    lines.append(
        f"        {name}_render_voices_block({name}_render_bus0{tap_arg}, 0u, {n0}u, b, frames);"
    )
    lines.append(f"        FM1_CSYNC(); {name}_render_bus0_ready = 1;")
    lines.append("        if (!dispatched || fm1_cpu1_join() != 0) {")
    lines.append(
        f"            {name}_render_voices_block({name}_render_bus1{tap_arg1}, {n0}u, NVOICE, b, frames);"
    )
    lines.append(f"            for (uint32_t f = b; f < b + {cb}u && f < frames; f++)")
    lines.append(
        f"                {name}_render_bus0[f - b] = fm1_sat_add32({name}_render_bus0[f - b], {name}_render_bus1[f - b]);"
    )
    lines.append(
        f"            {name}_render_post_block(out, {name}_render_bus0, b, frames);"
    )
    lines.append("        }")
    if has_taps:
        lines.append(
            f"        for (uint32_t f = b; f < b + {cb}u && f < frames && f < UMETATE_DSP_BLOCK_FRAMES; f++)"
        )
        lines.append("            for (uint32_t k = 0; k < N_TAP_CH; k++)")
        lines.append(
            f"                {name}_tap0[k][f] = fm1_sat_add32({name}_tap0[k][f], {name}_tap1[k][f]);"
        )
    lines.append("    }")
    lines.append("}")
    lines.append("#endif")
    lines.append("")
    return lines


def _zone(
    order: list[str], by_id: dict[str, NodeInstance], audio_only: bool
) -> list[NodeInstance]:
    """The instances of `order` filtered to audio-rate (or control-rate)."""
    result: list[NodeInstance] = []
    for iid in order:
        i = by_id[iid]
        if i.is_audio_rate() == audio_only:
            result.append(i)
    return result


def _control_rate_nodes(
    graph: CompiledGraph, by_id: dict[str, NodeInstance]
) -> list[NodeInstance]:
    return [
        by_id[iid]
        for iid in graph.voice_order + graph.global_order
        if not by_id[iid].is_audio_rate()
    ]


def _voice_mix(
    graph: CompiledGraph, by_id: dict[str, NodeInstance], normal: list[NodeInstance]
) -> str | None:
    """The C expression for the voice signal summed into the bus."""
    if graph.voice_out is not None:
        inst = by_id[graph.voice_out.node]
        return inst.out_local(graph.voice_out.port)
    for i in reversed(normal):
        for port in ("audio", "out"):
            if port in i.spec.outs:
                return i.out_local(port)
    return None


def _final_out(graph: CompiledGraph, by_id: dict[str, NodeInstance]) -> str:
    """The C expression written to `out`: a global node feeding `out`, else the bus."""
    if graph.global_out is not None:
        return by_id[graph.global_out.node].out_local(graph.global_out.port)
    return "bus"


