def build_main(argv: list[str] | None = None) -> int:
    args = _parser_build().parse_args(argv)
    if shutil.which("cmake") is None:
        print("plugin-build: cmake is not on PATH", file=sys.stderr)
        return 1
    synth = args.synth.resolve()
    try:
        project = _project(synth)
        meta = load_meta(
            synth,
            project.name,
            product_name=args.product_name,
            bundle_id=args.bundle_id,
            manufacturer_code=args.manufacturer_code,
            plugin_code=args.plugin_code,
        )
        out = args.out or _BUILD / "plugin" / project.name
        files = _rendered_files(project, out, meta, synth, args.plugin_source)
    except GenError as exc:
        print(f"plugin-build: {exc}", file=sys.stderr)
        return 1

    _write(out, files)
    build = args.build_dir or out / "build"
    if args.clean and build.is_dir():
        shutil.rmtree(build)

    configure = [
        "cmake",
        "-S",
        str(out),
        "-B",
        str(build),
        "-DP1_BUILD_JUCE=ON",
        f"-DP1_BUILD_CLAP={'OFF' if args.no_clap else 'ON'}",
        f"-DCMAKE_BUILD_TYPE={args.config}",
        "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON",
    ]
    if args.deps_dir is not None:
        deps = args.deps_dir.resolve()
        juce = deps / "juce-src"
        clap = deps / "clap-juce-extensions-src"
        if not juce.is_dir():
            print(f"plugin-build: no JUCE source at {juce}", file=sys.stderr)
            return 1
        configure.append(f"-DFETCHCONTENT_SOURCE_DIR_JUCE={juce.as_posix()}")
        if not args.no_clap:
            if not clap.is_dir():
                print(f"plugin-build: no CLAP source at {clap}", file=sys.stderr)
                return 1
            configure.append(
                f"-DFETCHCONTENT_SOURCE_DIR_CLAP-JUCE-EXTENSIONS={clap.as_posix()}"
            )

    print(f"plugin-build: {out}")
    if _run(configure) != 0:
        print("plugin-build: configure failed", file=sys.stderr)
        return 1
    if (
        _run(
            [
                "cmake",
                "--build",
                str(build),
                "--config",
                args.config,
                "--parallel",
                str(args.jobs),
            ]
        )
        != 0
    ):
        print("plugin-build: build failed", file=sys.stderr)
        return 1
    if not args.no_tests and _ctest(build, args.config) != 0:
        print("plugin-build: tests failed", file=sys.stderr)
        return 1
    return 0


