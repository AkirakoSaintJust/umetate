def check_main(argv: list[str] | None = None) -> int:
    args = _parser_check().parse_args(argv)
    synth = args.synth.resolve()
    try:
        project = _project(synth)
        meta = load_meta(
            synth,
            project.name,
            product_name=args.product_name,
            bundle_id=args.bundle_id,
            manufacturer_code=args.manufacturer_code,
            plugin_code=args.plugin_code,
        )
        out = args.out or _BUILD / "plugin" / project.name
        files = _rendered_files(project, out, meta, synth, args.plugin_source)
    except GenError as exc:
        print(f"plugin-check: {exc}", file=sys.stderr)
        return 1

    if not args.no_sync:
        problems = _check(out, files)
        if problems:
            for problem in problems:
                print(f"plugin-check: {problem}", file=sys.stderr)
            print(
                "plugin-check: run `umetate plugin-generate` to refresh",
                file=sys.stderr,
            )
            return 1
        print(f"plugin-check: {out}/gen is current")

    build = args.build_dir
    if build is None:
        build = out / "build"
        legacy = _ROOT / "build" / "plugin-juce"
        if not build.is_dir() and legacy.is_dir():
            build = legacy
    if not build.is_dir():
        print(
            f"plugin-check: no build tree at {build}; run `umetate plugin-build`",
            file=sys.stderr,
        )
        return 1
    if shutil.which("ctest") is None:
        print("plugin-check: ctest is not on PATH", file=sys.stderr)
        return 1
    if _ctest(build, args.config) != 0:
        print("plugin-check: tests failed", file=sys.stderr)
        return 1
    return 0
