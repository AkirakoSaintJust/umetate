"""`umetate plugin-generate`, `plugin-build`, and `plugin-check`.

The plugin host is reusable. A project is a thin generated layer: the synth's
rendered C, a CMake file with the plugin identity, and a CMakeLists that points at
the host. `plugin-build` configures and builds that project. `plugin-check` runs
its tests and verifies the generated files are current.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import cast

from ._ir import GenError
from ._synthgen import GeneratedProject, generate_project

_ROOT = Path(__file__).resolve().parents[1]
_EXAMPLES = _ROOT / "examples"
_PLUGIN = _ROOT / "plugin"
_BUILD = _ROOT / "build"

_PLUGIN_KEYS = frozenset(
    {"product_name", "bundle_id", "manufacturer_code", "plugin_code"}
)


@dataclass(frozen=True)
class PluginMeta:
    """The identity JUCE needs for one plugin product."""

    product_name: str
    bundle_id: str
    manufacturer_code: str
    plugin_code: str


def _read_object(path: Path) -> dict[str, object]:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise GenError(f"cannot read {path}: {exc}") from exc
    if not isinstance(raw, dict):
        raise GenError(f"{path}: expected a JSON object")
    return cast(dict[str, object], raw)


def _default_plugin_code(cname: str) -> str:
    clean = "".join(ch for ch in cname if ch.isalnum())
    return ("P1" + clean)[:4].ljust(4, "0")


def _text(raw: dict[str, object], key: str, override: str | None, default: str) -> str:
    value: object = override if override is not None else raw.get(key, default)
    if not isinstance(value, str) or not value:
        raise GenError(f"plugin.json: {key} must be a non-empty string")
    if any(ord(ch) < 0x20 for ch in value):
        raise GenError(f"plugin.json: {key} contains a control character")
    if '"' in value or "\\" in value:
        raise GenError(f"plugin.json: {key} cannot contain quotes or backslashes")
    return value


def load_meta(
    synth: Path,
    cname: str,
    *,
    product_name: str | None = None,
    bundle_id: str | None = None,
    manufacturer_code: str | None = None,
    plugin_code: str | None = None,
) -> PluginMeta:
    """Read `plugin.json` (when present) and apply the CLI overrides."""
    path = synth / "plugin.json"
    raw = _read_object(path) if path.is_file() else {}
    unknown = sorted(set(raw) - _PLUGIN_KEYS)
    if unknown:
        raise GenError(f"{path}: unknown keys: {', '.join(unknown)}")

    meta = PluginMeta(
        product_name=_text(raw, "product_name", product_name, cname),
        bundle_id=_text(raw, "bundle_id", bundle_id, f"com.p1onken.{cname}"),
        manufacturer_code=_text(raw, "manufacturer_code", manufacturer_code, "P1on"),
        plugin_code=_text(raw, "plugin_code", plugin_code, _default_plugin_code(cname)),
    )
    for label, code in (
        ("manufacturer_code", meta.manufacturer_code),
        ("plugin_code", meta.plugin_code),
    ):
        if re.fullmatch(r"[A-Za-z0-9]{4}", code) is None:
            raise GenError(
                f"{path}: {label} must be exactly four ASCII letters or digits"
            )
    return meta


def _cmake_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _template(name: str) -> str:
    return (_ROOT / "templates" / "plugin" / name).read_text(encoding="utf-8")


def _rendered_files(
    project: GeneratedProject,
    out: Path,
    meta: PluginMeta,
    synth: Path,
    plugin_source: Path,
) -> dict[str, str]:
    """Every file `plugin-generate` owns, keyed by its path under `out`."""
    files: dict[str, str] = {
        f"gen/{filename}": content for filename, content in project.outputs.items()
    }
    project_cmake = "\n".join(
        [
            "# Generated by `umetate plugin-generate`. Do not edit.",
            'set(P1_SYNTH_GEN "${CMAKE_CURRENT_LIST_DIR}/gen")',
            f"set(P1_SYNTH_CNAME {_cmake_string(project.name)})",
            f"set(P1_PRODUCT_NAME {_cmake_string(meta.product_name)})",
            f"set(P1_PLUGIN_TARGET {_cmake_string(project.name)})",
            f"set(P1_BUNDLE_ID {_cmake_string(meta.bundle_id)})",
            f"set(P1_MANUFACTURER_CODE {_cmake_string(meta.manufacturer_code)})",
            f"set(P1_PLUGIN_CODE {_cmake_string(meta.plugin_code)})",
            f"set(P1_STATE_TREE_ID {_cmake_string(project.name)})",
            "",
        ]
    )
    files["P1Project.cmake"] = project_cmake
    files["CMakeLists.txt"] = (
        _template("CMakeLists.txt")
        .replace("@P1_PLUGIN_TARGET@", project.name)
        .replace("@P1_PLUGIN_SOURCE@", plugin_source.resolve().as_posix())
    )
    files["README.md"] = (
        _template("README.md")
        .replace("@P1_SYNTH_DIR@", synth.resolve().as_posix())
        .replace("@P1_PROJECT_DIR@", out.resolve().as_posix())
        .replace("@P1_PLUGIN_SOURCE@", plugin_source.resolve().as_posix())
        .replace("@P1_PRODUCT_NAME@", meta.product_name)
    )
    return files


def _write(out: Path, files: dict[str, str]) -> None:
    gen = out / "gen"
    if gen.is_dir():
        expected = {Path(name).name for name in files if name.startswith("gen/")}
        for path in gen.iterdir():
            if path.is_file() and path.name not in expected:
                path.unlink()
    for relative, text in files.items():
        path = out / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def _check(out: Path, files: dict[str, str]) -> list[str]:
    problems: list[str] = []
    for relative, expected in files.items():
        path = out / relative
        if not path.is_file():
            problems.append(f"missing {relative}")
        elif path.read_text(encoding="utf-8") != expected:
            problems.append(f"stale {relative}")
    gen = out / "gen"
    if gen.is_dir():
        expected_gen = {Path(name).name for name in files if name.startswith("gen/")}
        for path in sorted(gen.iterdir()):
            if path.is_file() and path.name not in expected_gen:
                problems.append(f"unexpected gen/{path.name}")
    return problems


def _project(synth: Path) -> GeneratedProject:
    return generate_project(synth)


def _parser_generate() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="umetate plugin-generate",
        description="render a synth project's plugin sources",
    )
    parser.add_argument(
        "--synth",
        type=Path,
        default=_EXAMPLES / "type-p-fm1",
        help="the project dir (default: examples/type-p-fm1)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        help="the generated project dir (default: build/plugin/<cname>)",
    )
    parser.add_argument(
        "--plugin-source",
        type=Path,
        default=_PLUGIN,
        help="the reusable plugin host (default: plugin/)",
    )
    parser.add_argument("--product-name", help="the DAW display name")
    parser.add_argument("--bundle-id", help="the JUCE bundle id")
    parser.add_argument("--manufacturer-code", help="four-character JUCE code")
    parser.add_argument("--plugin-code", help="four-character JUCE code")
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the generated project is current, do not write",
    )
    return parser


def generate_main(argv: list[str] | None = None) -> int:
    args = _parser_generate().parse_args(argv)
    synth = args.synth.resolve()
    try:
        project = _project(synth)
        meta = load_meta(
            synth,
            project.name,
            product_name=args.product_name,
            bundle_id=args.bundle_id,
            manufacturer_code=args.manufacturer_code,
            plugin_code=args.plugin_code,
        )
        out = args.out or _BUILD / "plugin" / project.name
        files = _rendered_files(project, out, meta, synth, args.plugin_source)
    except GenError as exc:
        print(f"plugin-generate: {exc}", file=sys.stderr)
        return 1

    if args.check:
        problems = _check(out, files)
        if problems:
            for problem in problems:
                print(f"plugin-generate: {problem}", file=sys.stderr)
            print(
                "plugin-generate: run `umetate plugin-generate` to refresh",
                file=sys.stderr,
            )
            return 1
        print(f"plugin-generate: {out} is current")
        return 0

    _write(out, files)
    print(f"plugin-generate: {out}")
    print(f"  {project.name}: {meta.product_name} ({meta.bundle_id})")
    return 0


def _run(cmd: list[str]) -> int:
    print("$ " + " ".join(cmd))
    try:
        return subprocess.run(cmd, cwd=_ROOT, check=False).returncode
    except FileNotFoundError:
        print(f"plugin-build: cannot run {cmd[0]!r}", file=sys.stderr)
        return 127


def _ctest(build: Path, config: str) -> int:
    return _run(
        [
            "ctest",
            "--test-dir",
            str(build),
            "-C",
            config,
            "--output-on-failure",
        ]
    )


